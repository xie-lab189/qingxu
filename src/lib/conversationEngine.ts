/* ---------------- 上下文连贯（处理「累 + 考试」这类递进语义） ---------------- */

function contextualReply(
  agentId: AgentId,
  input: string,
  history: ChatTurn[]
): string | null {
  const lastUser = [...history].reverse().find((t) => t.role === "user");
  if (!lastUser) return null;
  const prev = lastUser.content;
  const tiredPrev = /累|疲惫|困|倦|没劲|撑不住|不想动|崩/.test(prev);
  const examNow = /考试|复习|高数|明天|学习|作业|论文|课|备考|考研/.test(input);
  if (tiredPrev && examNow) {
    if (agentId === "planner") {
      return pick([
        "上一轮你说很累，这一轮又要面对考试——那更要做减法：今晚只复习最高频的考点，其余先放一放。",
        "累着还要备考最磨人。建议把今晚拆成两个 25 分钟，中间强制休息，能撑住就不错。",
      ]);
    }
    if (agentId === "supervisor") {
      return pick([
        "知道你累，但考试不等人对吧？那咱们不搞大阵仗，就复习 20 分钟最核心的内容，然后立刻睡觉！",
        "累归累，明天的考试咱们还是得怼。先做 5 分钟热身，进入状态就不那么难受了，冲！",
      ]);
    }
    return pick([
      "我知道你现在很累，但为了明天的考试还在坚持，这本身就很了不起。要不我们先把复习任务减半，或者挑最重要的看？",
      "你累着还想撑完复习，真的已经很努力了。先别贪多，今晚只看最核心的那几页，好吗？我陪着你。",
    ]);
  }
  return null;
}

/* ---------------- 是否有「具体事由」上下文 ----------------
 * 只有用户已经讲过具体的事（多轮对话，或本轮描述了较长的一段经历），
 * 才能 safely 使用「那会儿 / 后来 / 当时」这类回溯式追问，
 * 否则会问出「那会儿你心里是什么滋味？」这种毫无来由的话。 */
function hasStoryContext(history: ChatTurn[], current: string): boolean {
  const userTurns = history.filter((t) => t.role === "user");
  if (userTurns.length >= 2) return true; // 已经聊了好几句，算有上下文
  // 单轮但内容较长、像在讲一件事
  const last = userTurns[userTurns.length - 1];
  const sample = (last?.content ?? current).trim();
  return sample.length >= 15;
}

/* ---------------- 主入口：generateReply ---------------- */

/**
 * 生成智能体回复（纯本地计算，绝不抛错、绝不发起网络请求）。
 * 通过「意图 → 整句语料 + 话题呼应 + 偶发轻柔追问/简短回应」让对话更自然。
 *
 * @param agentId   当前智能体
 * @param userInput 用户本次输入
 * @param history   历史对话（不含本次输入），引擎内部只取最近 3 轮
 * @returns 一段自然语言回复
 */
export function generateReply(
  agentId: AgentId,
  userInput: string,
  history: ChatTurn[] = []
): string {
  try {
    const recent = history.slice(-6); // 最近 3 轮（每轮 user+agent）
    const t = userInput.trim();

    // 1) 上下文连贯优先（如「累」接「考试」）
    const ctx = contextualReply(agentId, t, recent);
    if (ctx) return ctx;

    // 2) 被批评 / 被否定：走接纳红线
    if (/老师|教授|导师|被骂|骂我|批评|被说|被讲|被否定|被指责|被diss/.test(t)) {
      return teacherReply(agentId);
    }

    // 3) 危机：严肃安抚语原样返回，不加追问，避免稀释紧急感
    const intent = detectIntent(t);
    if (intent === "crisis") {
      return pick(CRISIS_REPLIES);
    }

    const pool = POOLS[agentId];
    let reply: string;

    // 4) 陪伴者对极短/随意输入，偶尔用极简短回应，像真人在随口接话
    if (
      agentId === "companion" &&
      intent === "fallback" &&
      t.length <= 6 &&
      Math.random() < 0.4 &&
      pool.brief
    ) {
      reply = pick(pool.brief);
    } else {
      reply = pick(pool[intent]);
    }

    // 5) 话题呼应：把 {topic} 替换为具体内容，让共情更「接得住」
    const topic = detectTopic(t);
    reply = reply.replace(/\{topic\}/g, topic || "这些事");

    // 6) 偶发轻柔追问（只在合适意图、且本句还没以问号结尾时追加），制造自然节奏
    //    关键：永远保留句子边界，绝不让追问与上句粘连成一句话；
    //    且「那会儿 / 后来 / 当时」这类回溯式追问，仅在用户已讲过具体事由时才可用。
    const canFollow =
      intent === "stress" || intent === "fallback" || intent === "question";
    const endsWithQuestion = /[?？]$/.test(reply.trim());
    if (canFollow && !endsWithQuestion && Math.random() < 0.45) {
      const candidates = hasStoryContext(recent, t)
        ? [...pool.followup, ...(pool.followupCtx ?? [])]
        : pool.followup;
      const f = pick(candidates);
      const base = reply.trim();
      reply = /[。！？.!?]$/.test(base) ? base + f : base + "，" + f;
    }

    return reply.length > 0 ? reply : pick(pool.fallback);
  } catch {
    // 任何意外都兜底，绝不把错误暴露给用户
    return "我在呢，你慢慢说，我都在听。";
  }
}
