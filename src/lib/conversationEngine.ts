/**
 * 青序 · 纯本地「高拟真对话引擎」
 *
 * 完全离线运行：没有任何 fetch / 网络请求 / 外部 API 依赖，断网也能流畅聊天。
 * 通过「多维意图识别 + 三大人设语料 + 自然语言拼接（话题呼应 + 偶尔简短回应 +
 * 轻柔追问）」生成大量不重复的回复，并维护最近 3 轮上下文记忆，使对话连贯自然。
 *
 * 设计红线：无条件接纳、绝不评判事实对错或「站队」。
 */

import type { AgentId } from "@/agents/config";

/* ---------------- 基础工具 ---------------- */

function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 一轮对话（用于上下文记忆） */
export interface ChatTurn {
  role: "user" | "agent";
  content: string;
}

/* ---------------- 意图分类 ---------------- */

export type Intent = "crisis" | "greeting" | "stress" | "question" | "fallback";

/**
 * 模糊匹配 + 简单正则的意图识别。
 * 顺序很关键：危机 > 打招呼 > 倾诉/压力 > 提问 > 兜底。
 */
export function detectIntent(text: string): Intent {
  const t = text.trim();
  if (/崩溃|不想活|绝望|活不下去|想死|自杀|结束生命|活着没意思|活着好累|撑不住了|去死|不想活了/.test(t)) {
    return "crisis";
  }
  if (/你好|您好|在吗|在么|在不在|嗨|hi|hello|早|晚安|晚上好|下午好|早上好|无聊|有人吗|在不在呀|在不在啊/.test(t)) {
    return "greeting";
  }
  if (
    /累|疲惫|困|倦|烦|压力|老师|教授|导师|作业|考试|复习|高数|焦虑|难过|委屈|哭|孤独|失眠|熬夜|挂科|论文|学习|课|同学|舍友|宿舍|伤心|低落|抑郁|烦人|心情不好|不开心|不高兴|郁闷|压抑|烦闷|情绪低落|难受|想哭|绷不住|没精神|提不起劲/.test(t)
  ) {
    return "stress";
  }
  if (/[?？]|吗|怎么|为什么|为何|如何|怎样|是不是|怎么办|什么|哪些|多少|好吗|行吗/.test(t)) {
    return "question";
  }
  return "fallback";
}

/* ---------------- 话题识别（让共情更具体，不那么空泛） ---------------- */

const TOPIC_PATTERNS: [RegExp, string][] = [
  [/考试|高数|复习|备考|期末|考研|挂科/, "考试"],
  [/作业|论文|毕设|课题|项目|deadline|截止/, "那些作业和任务"],
  [/老师|教授|导师/, "老师"],
  [/朋友|闺蜜|兄弟|同学|舍友|室友|同桌/, "朋友之间"],
  [/爸妈|父母|家里|家人|家长|回家/, "家里"],
  [/失眠|睡不好|熬夜|睡不着|多梦|没睡/, "睡不好"],
  [/分手|暗恋|喜欢的人|对象|男朋友|女朋友|恋爱|单身/, "感情"],
  [/胖|丑|身材|容貌|长相|颜值/, "对自己的样子"],
  [/工作|实习|面试|老板|同事|加班/, "工作"],
];

/** 抽取一句话里最突出的话题词，用于让陪伴者「接得住」具体内容 */
function detectTopic(text: string): string {
  for (const [re, word] of TOPIC_PATTERNS) {
    if (re.test(text)) return word;
  }
  return "";
}

